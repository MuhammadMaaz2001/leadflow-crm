import { Prisma } from '@leadflow/database';
import { fullName } from '@leadflow/shared';
import { addDays, differenceInCalendarDays } from 'date-fns';
import { db } from '../../db';
import { resolveRange } from '../../lib/dates';
import { lite, usersById } from '../../lib/users';
import type { Ctx } from '../../http';
import { type FilterCtx } from './filters';
import { followUpScope } from '../followups/service';

const n = (v: unknown) => Number(v ?? 0);
const pct = (a: number, b: number) => (b > 0 ? Math.round((a / b) * 1000) / 10 : 0);

export type Granularity = 'day' | 'week' | 'month';
export function granularityFor(f: FilterCtx): Granularity {
  const days = differenceInCalendarDays(f.range.to, f.range.from);
  return days > 400 ? 'month' : days > 100 ? 'week' : 'day';
}

/** Zero-fill missing buckets so charts show empty periods (bucket keys generated by PostgreSQL in the workspace timezone). */
export async function bucketKeys(f: FilterCtx, g: Granularity): Promise<string[]> {
  const end = f.range.to < f.now ? f.range.to : new Date(f.now.getTime() + 86_400_000);
  const rows = await db().$queryRaw<Array<{ k: string }>>`
    SELECT to_char(d, 'YYYY-MM-DD') AS k FROM generate_series(
      date_trunc(${Prisma.raw(`'${g}'`)}, ${f.range.from}::timestamptz AT TIME ZONE ${f.tz}),
      date_trunc(${Prisma.raw(`'${g}'`)}, (${end}::timestamptz - interval '1 second') AT TIME ZONE ${f.tz}),
      ${Prisma.raw(`interval '1 ${g}'`)}) d LIMIT 800`;
  return rows.map((r) => r.k);
}
export function fillBuckets<T extends { bucket: string }>(rows: T[], keys: string[], zero: Omit<T, 'bucket'>): T[] {
  const map = new Map(rows.map((r) => [r.bucket, r]));
  return keys.map((k) => (map.get(k) ?? ({ bucket: k, ...zero } as T)));
}

export function trunc(g: Granularity, col: string, tz: string) {
  return Prisma.sql`to_char(date_trunc(${Prisma.raw(`'${g}'`)}, ${Prisma.raw(col)} AT TIME ZONE ${tz}), 'YYYY-MM-DD')`;
}

export async function buildDashboard(ctx: Ctx, f: FilterCtx) {
  const g = granularityFor(f);
  const keys = await bucketKeys(f, g);
  const { from, to } = f.range;
  const now = f.now;
  const today = resolveRange('today', f.tz);
  const scopeFU = followUpScope(ctx);
  const fuAssignee = f.assigneeId ? { assignedToId: f.assigneeId } : {};
  const fuBase: Prisma.FollowUpWhereInput = { organizationId: ctx.orgId, ...fuAssignee, AND: [scopeFU] };

  const [kpiRow] = await db().$queryRaw<Array<Record<string, bigint>>>`
    SELECT count(*) AS total,
           count(*) FILTER (WHERE l.status = 'NEW') AS new_leads,
           count(*) FILTER (WHERE l.assigned_to_id IS NULL) AS unassigned,
           count(*) FILTER (WHERE l.assigned_to_id IS NOT NULL) AS assigned,
           count(*) FILTER (WHERE l.first_contacted_at IS NOT NULL) AS contacted
    FROM leads l WHERE ${f.leadWhere}`;
  const [wl] = await db().$queryRaw<Array<Record<string, bigint>>>`
    SELECT count(*) FILTER (WHERE l.converted_at >= ${from} AND l.converted_at < ${to}) AS won,
           count(*) FILTER (WHERE l.lost_at >= ${from} AND l.lost_at < ${to}) AS lost
    FROM leads l WHERE ${f.leadAnyWhere}`;
  const [closed] = await db().$queryRaw<Array<Record<string, bigint | null>>>`
    SELECT count(*) FILTER (WHERE o.status = 'WON' AND o.won_at >= ${from} AND o.won_at < ${to}) AS won,
           count(*) FILTER (WHERE o.status = 'LOST' AND o.lost_at >= ${from} AND o.lost_at < ${to}) AS lost,
           COALESCE(sum(o.value) FILTER (WHERE o.status = 'WON' AND o.won_at >= ${from} AND o.won_at < ${to}), 0) AS won_value
    FROM opportunities o JOIN leads l ON l.id = o.lead_id AND l.organization_id = o.organization_id WHERE ${f.oppWhere}`;
  const [dueToday, overdue, completedInRange] = await Promise.all([
    db().followUp.count({ where: { ...fuBase, status: 'PENDING', dueAt: { gte: today.from, lt: today.to } } }),
    db().followUp.count({ where: { ...fuBase, status: 'PENDING', dueAt: { lt: now } } }),
    db().followUp.count({ where: { ...fuBase, status: 'COMPLETED', completedAt: { gte: from, lt: to } } }),
  ]);
  const wonOpps = n(closed?.won), lostOpps = n(closed?.lost);

  const leadsSeries = await db().$queryRaw<Array<{ bucket: string; leads: bigint; won: bigint }>>`
    SELECT ${trunc(g, 'l.created_at', f.tz)} AS bucket, count(*) AS leads, count(*) FILTER (WHERE l.status = 'CONVERTED') AS won
    FROM leads l WHERE ${f.leadWhere} GROUP BY 1 ORDER BY 1`;
  const bySource = await db().$queryRaw<Array<{ id: string | null; name: string | null; color: string | null; leads: bigint; won: bigint; contacted: bigint }>>`
    SELECT s.id, s.name, s.color, count(*) AS leads, count(*) FILTER (WHERE l.status = 'CONVERTED') AS won, count(*) FILTER (WHERE l.first_contacted_at IS NOT NULL) AS contacted
    FROM leads l LEFT JOIN lead_sources s ON s.id = l.source_id AND s.organization_id = l.organization_id
    WHERE ${f.leadWhere} GROUP BY s.id, s.name, s.color ORDER BY count(*) DESC`;

  const pipeline = f.pipelineId
    ? await db().pipeline.findFirst({ where: { id: f.pipelineId, organizationId: ctx.orgId, archivedAt: null } })
    : await db().pipeline.findFirst({ where: { organizationId: ctx.orgId, isDefault: true, archivedAt: null } });
  const pipeWhere = Prisma.sql`o.organization_id = ${ctx.orgId}::uuid AND o.archived_at IS NULL${f.assigneeId ? Prisma.sql` AND o.owner_id = ${f.assigneeId}::uuid` : Prisma.empty}${f.sourceId ? Prisma.sql` AND l.source_id = ${f.sourceId}::uuid` : Prisma.empty}`;
  const stagesDist = pipeline ? await db().$queryRaw<Array<{ id: string; name: string; color: string; kind: string; position: number; count: bigint; value: bigint | null }>>`
    SELECT st.id, st.name, st.color, st.kind::text, st.position, count(o.id) AS count, COALESCE(sum(o.value), 0) AS value
    FROM pipeline_stages st
    LEFT JOIN (SELECT o.* FROM opportunities o JOIN leads l ON l.id = o.lead_id AND l.organization_id = o.organization_id WHERE ${pipeWhere}) o ON o.stage_id = st.id AND o.organization_id = st.organization_id
    WHERE st.pipeline_id = ${pipeline.id}::uuid AND st.organization_id = ${ctx.orgId}::uuid GROUP BY st.id ORDER BY st.position` : [];

  const wonLost = await db().$queryRaw<Array<{ bucket: string; won: bigint; lost: bigint; won_value: bigint | null }>>`
    SELECT b AS bucket, sum(w) AS won, sum(x) AS lost, sum(v) AS won_value FROM (
      SELECT ${trunc(g, 'o.won_at', f.tz)} AS b, 1 AS w, 0 AS x, o.value AS v FROM opportunities o JOIN leads l ON l.id = o.lead_id AND l.organization_id = o.organization_id WHERE ${f.oppWhere} AND o.status = 'WON' AND o.won_at >= ${from} AND o.won_at < ${to}
      UNION ALL
      SELECT ${trunc(g, 'o.lost_at', f.tz)}, 0, 1, 0 FROM opportunities o JOIN leads l ON l.id = o.lead_id AND l.organization_id = o.organization_id WHERE ${f.oppWhere} AND o.status = 'LOST' AND o.lost_at >= ${from} AND o.lost_at < ${to}
    ) t GROUP BY b ORDER BY b`;

  const monthly = await db().$queryRaw<Array<{ bucket: string; won: bigint; lost: bigint }>>`
    SELECT b AS bucket, sum(w) AS won, sum(x) AS lost FROM (
      SELECT to_char(date_trunc('month', o.won_at AT TIME ZONE ${f.tz}), 'YYYY-MM-01') AS b, 1 AS w, 0 AS x FROM opportunities o JOIN leads l ON l.id = o.lead_id AND l.organization_id = o.organization_id WHERE ${f.oppWhere} AND o.status = 'WON' AND o.won_at >= ${addDays(now, -365)}
      UNION ALL
      SELECT to_char(date_trunc('month', o.lost_at AT TIME ZONE ${f.tz}), 'YYYY-MM-01'), 0, 1 FROM opportunities o JOIN leads l ON l.id = o.lead_id AND l.organization_id = o.organization_id WHERE ${f.oppWhere} AND o.status = 'LOST' AND o.lost_at >= ${addDays(now, -365)}
    ) t GROUP BY b ORDER BY b DESC LIMIT 12`;

  const perf = await salespersonStats(f, ctx);

  const [fuDue] = await db().$queryRaw<Array<Record<string, bigint>>>`
    SELECT count(*) FILTER (WHERE status = 'COMPLETED') AS completed,
           count(*) FILTER (WHERE status = 'COMPLETED' AND completed_at <= due_at) AS on_time,
           count(*) FILTER (WHERE status = 'PENDING' AND due_at < ${now}) AS overdue,
           count(*) FILTER (WHERE status = 'PENDING' AND due_at >= ${now}) AS upcoming
    FROM follow_ups WHERE organization_id = ${ctx.orgId}::uuid AND status <> 'CANCELED' AND due_at >= ${from} AND due_at < ${to}
    ${f.assigneeId ? Prisma.sql`AND assigned_to_id = ${f.assigneeId}::uuid` : Prisma.empty}
    ${ctx.can('followups.view_all') ? Prisma.empty : Prisma.sql`AND (assigned_to_id = ${ctx.userId}::uuid OR created_by_id = ${ctx.userId}::uuid)`}`;

  const aging = await db().$queryRaw<Array<{ bucket: string; count: bigint }>>`
    SELECT CASE WHEN age < 1 THEN '0-1d' WHEN age < 4 THEN '2-3d' WHEN age < 8 THEN '4-7d' WHEN age < 15 THEN '8-14d' WHEN age < 31 THEN '15-30d' ELSE '30d+' END AS bucket, count(*) AS count
    FROM (SELECT EXTRACT(EPOCH FROM (${now}::timestamptz - l.created_at)) / 86400 AS age FROM leads l WHERE ${f.leadAnyWhere} AND l.status IN ('NEW','CONTACTED','QUALIFIED')) t GROUP BY 1`;
  const agingOrder = ['0-1d', '2-3d', '4-7d', '8-14d', '15-30d', '30d+'];

  const overdueList = await db().followUp.findMany({ where: { ...fuBase, status: 'PENDING', dueAt: { lt: now } }, include: { lead: { select: { id: true, firstName: true, lastName: true, companyName: true } } }, orderBy: { dueAt: 'asc' }, take: 6 });
  const todayList = await db().followUp.findMany({ where: { ...fuBase, status: 'PENDING', dueAt: { gte: today.from, lt: today.to } }, include: { lead: { select: { id: true, firstName: true, lastName: true, companyName: true } } }, orderBy: { dueAt: 'asc' }, take: 6 });
  const uncontacted = await db().lead.findMany({ where: { organizationId: ctx.orgId, archivedAt: null, mergedIntoId: null, firstContactedAt: null, status: 'NEW', ...(f.assigneeId ? { assignedToId: f.assigneeId } : {}), AND: [ctx.can('leads.view_all') ? {} : { OR: [{ assignedToId: ctx.userId }, { createdById: ctx.userId }] }] }, orderBy: { createdAt: 'asc' }, take: 5, select: { id: true, firstName: true, lastName: true, companyName: true, createdAt: true } });
  const recent = await db().activity.findMany({
    where: { organizationId: ctx.orgId, ...(ctx.can('activity.view_all') && !f.assigneeId ? {} : { actorId: f.assigneeId ?? ctx.userId }) },
    orderBy: { occurredAt: 'desc' }, take: 10, include: { lead: { select: { id: true, firstName: true, lastName: true } } },
  });
  const users = await usersById([...overdueList.map((x) => x.assignedToId), ...todayList.map((x) => x.assignedToId), ...recent.map((r) => r.actorId)]);
  const fuShape = (x: (typeof overdueList)[number]) => ({ id: x.id, type: x.type, dueAt: x.dueAt, priority: x.priority, lead: { id: x.lead.id, name: fullName(x.lead), companyName: x.lead.companyName }, assignedTo: lite(users, x.assignedToId) });

  const total = n(kpiRow?.total);
  return {
    filters: { from, to, range: f.range.preset, assigneeId: f.assigneeId, sourceId: f.sourceId, pipelineId: pipeline?.id ?? null, restricted: f.restricted, granularity: g, timezone: f.tz },
    kpis: {
      totalLeads: total, newLeads: n(kpiRow?.new_leads), unassignedLeads: n(kpiRow?.unassigned), assignedLeads: n(kpiRow?.assigned), contactedLeads: n(kpiRow?.contacted),
      contactRate: pct(n(kpiRow?.contacted), n(kpiRow?.assigned)),
      followUpsDueToday: dueToday, overdueFollowUps: overdue, followUpsCompleted: completedInRange,
      wonLeads: n(wl?.won), lostLeads: n(wl?.lost), wonOpportunities: wonOpps, lostOpportunities: lostOpps, wonValue: n(closed?.won_value),
      conversionRate: pct(wonOpps, wonOpps + lostOpps),
    },
    leadsOverTime: fillBuckets(leadsSeries.map((r) => ({ bucket: r.bucket, leads: n(r.leads), won: n(r.won) })), keys, { leads: 0, won: 0 }),
    leadsBySource: bySource.map((r) => ({ id: r.id, name: r.name ?? 'Unknown', color: r.color ?? '#94a3b8', leads: n(r.leads), won: n(r.won), contacted: n(r.contacted) })),
    pipeline: { id: pipeline?.id ?? null, name: pipeline?.name ?? null, stages: stagesDist.map((s) => ({ id: s.id, name: s.name, color: s.color, kind: s.kind, count: n(s.count), value: n(s.value) })) },
    wonVsLost: fillBuckets(wonLost.map((r) => ({ bucket: r.bucket, won: n(r.won), lost: n(r.lost), wonValue: n(r.won_value) })), keys, { won: 0, lost: 0, wonValue: 0 }),
    monthlyConversion: monthly.reverse().map((r) => ({ bucket: r.bucket, won: n(r.won), lost: n(r.lost), rate: pct(n(r.won), n(r.won) + n(r.lost)) })),
    salespersonPerformance: perf,
    followUpCompletion: { completed: n(fuDue?.completed), onTime: n(fuDue?.on_time), overdue: n(fuDue?.overdue), upcoming: n(fuDue?.upcoming), rate: pct(n(fuDue?.completed), n(fuDue?.completed) + n(fuDue?.overdue)) },
    leadAging: agingOrder.map((b) => ({ bucket: b, count: n(aging.find((a) => a.bucket === b)?.count) })),
    attention: {
      overdue: overdueList.map(fuShape), dueToday: todayList.map(fuShape),
      uncontacted: uncontacted.map((l) => ({ id: l.id, name: fullName(l), companyName: l.companyName, createdAt: l.createdAt })),
    },
    recentActivity: recent.map((r) => ({ id: r.id, type: r.type, title: r.title, occurredAt: r.occurredAt, actor: lite(users, r.actorId), lead: r.lead ? { id: r.lead.id, name: fullName(r.lead) } : null })),
  };
}

/** Per-salesperson funnel stats used by the dashboard chart, team page and performance report. */
export async function salespersonStats(f: FilterCtx, ctx: Ctx) {
  const { from, to } = f.range;
  const rows = await db().$queryRaw<Array<Record<string, string | bigint | null>>>`
    WITH members AS (
      SELECT m.user_id, u.name FROM memberships m JOIN users u ON u.id = m.user_id WHERE m.organization_id = ${ctx.orgId}::uuid AND m.status = 'ACTIVE'
      ${f.assigneeId ? Prisma.sql`AND m.user_id = ${f.assigneeId}::uuid` : Prisma.empty}
    ), lead_stats AS (
      SELECT l.assigned_to_id AS uid, count(*) AS leads, count(*) FILTER (WHERE l.first_contacted_at IS NOT NULL) AS contacted,
             avg(EXTRACT(EPOCH FROM (l.first_contacted_at - l.created_at)) / 3600) FILTER (WHERE l.first_contacted_at IS NOT NULL) AS avg_response_h
      FROM leads l WHERE ${f.leadWhere} AND l.assigned_to_id IS NOT NULL GROUP BY 1
    ), opp_stats AS (
      SELECT o.owner_id AS uid,
             count(*) FILTER (WHERE o.status = 'WON' AND o.won_at >= ${from} AND o.won_at < ${to}) AS won,
             count(*) FILTER (WHERE o.status = 'LOST' AND o.lost_at >= ${from} AND o.lost_at < ${to}) AS lost,
             COALESCE(sum(o.value) FILTER (WHERE o.status = 'WON' AND o.won_at >= ${from} AND o.won_at < ${to}), 0) AS won_value,
             count(*) FILTER (WHERE o.status = 'OPEN') AS open_opps
      FROM opportunities o JOIN leads l ON l.id = o.lead_id AND l.organization_id = o.organization_id WHERE ${f.oppWhere} GROUP BY 1
    ), fu_stats AS (
      SELECT assigned_to_id AS uid, count(*) FILTER (WHERE status = 'COMPLETED' AND completed_at >= ${from} AND completed_at < ${to}) AS fu_completed
      FROM follow_ups WHERE organization_id = ${ctx.orgId}::uuid GROUP BY 1
    )
    SELECT m.user_id AS id, m.name, COALESCE(ls.leads, 0) AS leads, COALESCE(ls.contacted, 0) AS contacted, ls.avg_response_h,
           COALESCE(os.won, 0) AS won, COALESCE(os.lost, 0) AS lost, COALESCE(os.won_value, 0) AS won_value, COALESCE(os.open_opps, 0) AS open_opps, COALESCE(fs.fu_completed, 0) AS fu_completed
    FROM members m LEFT JOIN lead_stats ls ON ls.uid = m.user_id LEFT JOIN opp_stats os ON os.uid = m.user_id LEFT JOIN fu_stats fs ON fs.uid = m.user_id
    ORDER BY COALESCE(os.won_value, 0) DESC, COALESCE(ls.leads, 0) DESC`;
  return rows.map((r) => ({
    id: String(r.id), name: String(r.name), leads: n(r.leads), contacted: n(r.contacted), contactRate: pct(n(r.contacted), n(r.leads)), avgResponseHours: r.avg_response_h == null ? null : Math.round(Number(r.avg_response_h) * 10) / 10,
    won: n(r.won), lost: n(r.lost), wonValue: n(r.won_value), openOpportunities: n(r.open_opps), conversionRate: pct(n(r.won), n(r.won) + n(r.lost)), followUpsCompleted: n(r.fu_completed),
  }));
}
export { pct, n as num };
